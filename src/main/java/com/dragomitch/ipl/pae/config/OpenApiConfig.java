/**
 * The OpenAPI 3 document of the REST API ({@code GET /v3/api-docs}) and the Swagger UI that renders
 * it ({@code /swagger-ui.html}), generated by springdoc-openapi from the controllers of {@code
 * adapter.in.web} ({@code springdoc.paths-to-match} keeps it to {@code /api/**}). Both are public
 * ({@code SecurityConfig}): they describe the API and hold no data.
 *
 * <p>A new endpoint appears in the document by itself, with its parameters, its Bean Validation
 * constraints and its JSON types; {@code OpenApiDocumentTest} fails when a mapping of the
 * controllers is missing. What springdoc cannot see is added here, once for every operation:
 *
 * <ul>
 *   <li>the authentication: the {@value SessionCookieService#COOKIE_NAME} cookie holding the
 *       session JWT (an API client may send the same token in an {@code Authorization: Bearer}
 *       header), and the {@value #CSRF_HEADER_NAME} header that every state-changing request must
 *       carry (the value of the {@code XSRF-TOKEN} cookie). An operation without
 *       {@code @PreAuthorize} is public;
 *   <li>the error responses, all of them RFC 9457 problems rendered by {@link ApiExceptionHandler}
 *       and described by the {@value #PROBLEM_DETAIL} schema (the standard members plus {@code
 *       code}, {@code errors}, {@code timestamp} and {@code errorId}).
 * </ul>
 *
 * <p>The version of the document is the version of the build ({@code BuildProperties}, written by
 * the {@code build-info} goal of the Spring Boot Maven plugin), or {@value #DEV_VERSION} when the
 * application runs without it (from an IDE).
 */
@Configuration(proxyBeanMethods = false)
public class OpenApiConfig {

  /** Title of the document. */
  public static final String TITLE = "Erasmus Management Application API";

  /** Version of the document when the build information is missing. */
  public static final String DEV_VERSION = "dev";

  /** Security scheme: the session cookie. */
  public static final String SESSION_COOKIE = "sessionCookie";

  /** Security scheme: the CSRF header of the state-changing requests. */
  public static final String CSRF_HEADER = "csrfHeader";

  /** The header carrying the CSRF token ({@code CookieCsrfTokenRepository}'s default). */
  public static final String CSRF_HEADER_NAME = "X-XSRF-TOKEN";

  /** Name of the schema of the error responses. */
  public static final String PROBLEM_DETAIL = "ProblemDetail";

  /** Reference to the schema of the error responses. */
  public static final String PROBLEM_DETAIL_REF =
      Components.COMPONENTS_SCHEMAS_REF + PROBLEM_DETAIL;

  /** The methods that change nothing, hence need no CSRF token. */
  private static final Set<RequestMethod> SAFE_METHODS =
      EnumSet.of(RequestMethod.GET, RequestMethod.HEAD, RequestMethod.OPTIONS);

  static {
    // the signed-in user is resolved from the session (CurrentUserArgumentResolver): it is not a
    // parameter the client sends
    SpringDocUtils.getConfig().addRequestWrapperToIgnore(CurrentUser.class);
  }

  /**
   * The document: title, version, security schemes and the problem schema.
   *
   * @param buildProperties the build information, when the jar was built by Maven
   * @return the base of the document, completed by springdoc
   */
  @Bean
  public OpenAPI openApi(ObjectProvider<BuildProperties> buildProperties) {
    String version =
        Optional.ofNullable(buildProperties.getIfAvailable())
            .map(BuildProperties::getVersion)
            .orElse(DEV_VERSION);
    return new OpenAPI()
        .info(
            new Info()
                .title(TITLE)
                .version(version)
                .description(
                    "REST API of the Erasmus Management Application (EMA): sign-in, users, "
                        + "mobility choices, mobilities, partners and reference data. Sign in with "
                        + "`POST /api/1.0/session`: the response sets the `session` cookie, which the "
                        + "browser then sends with every call. State-changing requests also need the "
                        + "`X-XSRF-TOKEN` header, holding the value of the `XSRF-TOKEN` cookie. Errors "
                        + "are RFC 9457 problems (`application/problem+json`, schema `ProblemDetail`), "
                        + "localized from `Accept-Language` (fr, en)."))
        .components(
            new Components()
                .addSecuritySchemes(
                    SESSION_COOKIE,
                    new SecurityScheme()
                        .type(SecurityScheme.Type.APIKEY)
                        .in(SecurityScheme.In.COOKIE)
                        .name(SessionCookieService.COOKIE_NAME)
                        .description(
                            "The session JWT, set by `POST /api/1.0/session` (HttpOnly cookie). "
                                + "API clients may send the same token in an `Authorization: Bearer` header."))
                .addSecuritySchemes(
                    CSRF_HEADER,
                    new SecurityScheme()
                        .type(SecurityScheme.Type.APIKEY)
                        .in(SecurityScheme.In.HEADER)
                        .name(CSRF_HEADER_NAME)
                        .description(
                            "The value of the `XSRF-TOKEN` cookie, required on every "
                                + "state-changing request (POST, PUT, DELETE), sign-in included, unless the "
                                + "session token is sent in an `Authorization: Bearer` header."))
                .addSchemas(PROBLEM_DETAIL, problemDetailSchema()))
        .addSecurityItem(new SecurityRequirement().addList(SESSION_COOKIE));
  }

  /**
   * Gives every operation its security requirements and its error responses.
   *
   * @return the customizer
   */
  @Bean
  public OperationCustomizer securityAndErrorResponses() {
    return OpenApiConfig::customize;
  }

  /**
   * Completes an operation from its handler:
   *
   * <ul>
   *   <li>security: the session cookie when the handler (or its controller) has a
   *       {@code @PreAuthorize} role check, the CSRF header when the method changes state; nothing
   *       for a public read;
   *   <li>400 when the operation takes parameters or a body (constraints, unreadable values), 401
   *       when it needs a session, 403 when it has a role check or needs the CSRF token, 404 when
   *       the path names a resource, 409 and 422 when it changes state (stale version or state
   *       conflict, business rule). Every 4xx response, those declared by an annotation included,
   *       is a {@value #PROBLEM_DETAIL} ({@code application/problem+json}).
   * </ul>
   *
   * @param operation the operation built by springdoc
   * @param handler its controller method
   * @return the operation
   */
  static Operation customize(Operation operation, HandlerMethod handler) {
    boolean sessionRequired =
        AnnotatedElementUtils.hasAnnotation(handler.getMethod(), PreAuthorize.class)
            || AnnotatedElementUtils.hasAnnotation(handler.getBeanType(), PreAuthorize.class);
    boolean stateChanging = changesState(handler);

    SecurityRequirement requirement = new SecurityRequirement();
    if (sessionRequired) {
      requirement.addList(SESSION_COOKIE);
    }
    if (stateChanging) {
      requirement.addList(CSRF_HEADER);
    }
    operation.setSecurity(requirement.isEmpty() ? List.of() : List.of(requirement));

    List<Parameter> parameters = Optional.ofNullable(operation.getParameters()).orElse(List.of());
    ApiResponses responses =
        Optional.ofNullable(operation.getResponses()).orElseGet(ApiResponses::new);
    operation.setResponses(responses);
    if (!parameters.isEmpty() || operation.getRequestBody() != null) {
      addError(
          responses,
          "400",
          "Invalid request: a broken constraint (VALIDATION_FAILED, the "
              + "fields in `errors`) or an unreadable body or parameter (MALFORMED_REQUEST)");
    }
    if (sessionRequired) {
      addError(responses, "401", "No valid session (UNAUTHENTICATED)");
    }
    if (sessionRequired || stateChanging) {
      addError(
          responses,
          "403",
          "Role not allowed, or CSRF token missing or invalid " + "(ACCESS_DENIED)");
    }
    if (parameters.stream().anyMatch(parameter -> "path".equals(parameter.getIn()))) {
      addError(responses, "404", "Unknown resource (RESOURCE_NOT_FOUND)");
    }
    if (stateChanging) {
      addError(
          responses,
          "409",
          "Conflict with the current state: stale version "
              + "(CONCURRENT_MODIFICATION), database constraint (DATA_CONFLICT) or a state rule "
              + "(e.g. MOBILITY_CANCELLED, USERNAME_TAKEN)");
      addError(
          responses,
          "422",
          "Business rule broken (e.g. UNKNOWN_COUNTRY, " + "DENIAL_REASON_REQUIRED)");
    }
    // whatever an annotation says, an error is a problem (ApiExceptionHandler renders them all)
    responses.forEach((status, response) -> {
      if (status.startsWith("4")) {
        response.setContent(problemContent());
      }
    });
    return operation;
  }

  /** Whether the handler serves a state-changing method (anything but GET, HEAD, OPTIONS). */
  private static boolean changesState(HandlerMethod handler) {
    RequestMapping mapping =
        AnnotatedElementUtils.findMergedAnnotation(handler.getMethod(), RequestMapping.class);
    RequestMethod[] methods = mapping == null ? new RequestMethod[0] : mapping.method();
    return Arrays.stream(methods).anyMatch(method -> !SAFE_METHODS.contains(method));
  }

  private static void addError(ApiResponses responses, String status, String description) {
    if (!responses.containsKey(status)) {
      responses.addApiResponse(status, new ApiResponse().description(description));
    }
  }

  private static Content problemContent() {
    return new Content()
        .addMediaType(
            org.springframework.http.MediaType.APPLICATION_PROBLEM_JSON_VALUE,
            new MediaType().schema(new Schema<>().$ref(PROBLEM_DETAIL_REF)));
  }

  /**
   * The schema of the problems of {@link ApiExceptionHandler}: the members of RFC 9457 and the
   * extension members of the API.
   *
   * @return the schema
   */
  static Schema<?> problemDetailSchema() {
    StringSchema code = new StringSchema();
    code.description(
        "The error code (an `ErrorCode` name), always present: the key clients " + "branch on.");
    code.setEnum(Arrays.stream(ErrorCode.values()).map(Enum::name).toList());
    Schema<?> fieldViolation =
        new ObjectSchema()
            .description("A broken constraint.")
            .addProperty(
                "field",
                new StringSchema()
                    .description(
                        "The property path of the value (`email`, `options[0].code`) or a "
                            + "parameter name."))
            .addProperty(
                "code",
                new StringSchema().description("The constraint (`NotBlank`, `Email`, `Size`...)."))
            .addProperty(
                "message",
                new StringSchema().description("The message, localized from `Accept-Language`."));
    return new ObjectSchema()
        .description(
            "An RFC 9457 problem (`application/problem+json`), the body of every error "
                + "response. `title` and `detail` are localized from `Accept-Language` (fr, en).")
        .addProperty(
            "type",
            new StringSchema()
                .format("uri")
                .description("`urn:pae:problem:<code>`.")
                .example("urn:pae:problem:username-taken"))
        .addProperty("title", new StringSchema().description("A short summary of the problem."))
        .addProperty("status", new IntegerSchema().description("The HTTP status code."))
        .addProperty(
            "detail",
            new StringSchema()
                .description(
                    "An explanation of this occurrence; a 5xx never describes the failure."))
        .addProperty(
            "instance", new StringSchema().format("uri").description("The path of the request."))
        .addProperty(ApiExceptionHandler.CODE, code)
        .addProperty(
            ApiExceptionHandler.ERRORS,
            new ArraySchema()
                .items(fieldViolation)
                .description("The broken constraints of a VALIDATION_FAILED problem."))
        .addProperty(
            ApiExceptionHandler.TIMESTAMP,
            new StringSchema().format("date-time").description("When the error occurred."))
        .addProperty(
            ApiExceptionHandler.ERROR_ID,
            new StringSchema()
                .format("uuid")
                .description("5xx only: the identifier of the error in the server log."))
        .required(
            List.of(
                "type",
                "title",
                "status",
                ApiExceptionHandler.CODE,
                ApiExceptionHandler.TIMESTAMP));
  }
}
